#!/usr/bin/env node
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { compressBytes, decompressBytes } from "../studio/core/compression.js";

const root = resolve(import.meta.dirname, "..");
if (!process.argv[2]) {
  console.error("usage: node tools/generate-mickey-120c-example.mjs <verified-mickey.vram>");
  process.exit(1);
}
const sourcePath = resolve(process.argv[2]);
const outputPath = resolve(root, "studio/examples-mickey-120c-assets.generated.js");
const vram = new Uint8Array(readFileSync(sourcePath));

assert.equal(vram.length, 0x4000, "Mickey capture must contain the complete 16 KB VRAM image");

const assets = [
  { path: "mickey-120c-bank-a.zx0", bytes: vram.slice(0x0000, 0x1800) },
  { path: "mickey-120c-name.zx0", bytes: vram.slice(0x1800, 0x1B00) },
  { path: "mickey-120c-bank-b.zx0", bytes: vram.slice(0x2000, 0x3800) }
];

const files = [];
for (const asset of assets) {
  const packed = new Uint8Array(await compressBytes("zx0", asset.bytes));
  const restored = new Uint8Array(await decompressBytes("zx0", packed));
  assert.deepEqual(restored, asset.bytes, `${asset.path} ZX0 round trip`);
  files.push({
    path: asset.path,
    kind: "picture",
    codec: "zx0",
    source: "example",
    base64: Buffer.from(packed).toString("base64")
  });
  console.log(`${asset.path}: ${asset.bytes.length} -> ${packed.length} bytes`);
}

const output = `// GENERATED by tools/generate-mickey-120c-example.mjs from the verified Mickey ROM VRAM capture.\n` +
  `export const mickey120cProjectFiles = ${JSON.stringify(files, null, 2)};\n`;
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
console.log(`Wrote ${outputPath}`);
