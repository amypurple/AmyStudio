#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadCodec } from "../studio/vendor/retrocompress-lite/js/codecConfig.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = path.join(root, "studio", "examples-src", "earth-globe-data.asm");
const output = path.join(root, "studio", "examples-earth-globe-assets.generated.js");
const source = fs.readFileSync(input, "utf8");
const zx0 = await loadCodec("zx0");
const originalTiles = [
  readDbLabel(source, "RESERVED_TILE_00_VOID", 8),
  ...splitTiles(readDbLabel(source, "EARTH_PATTERN_TILES", 2032)),
  readDbLabel(source, "RESERVED_TILE_FF_OCEAN", 8),
];
const originalFrames = Array.from({ length: 12 }, (_, index) =>
  readDbLabel(source, `FRAME_${String(index * 2).padStart(2, "0")}H_MAP`, 64));
const order = await optimizeTileOrder(originalTiles, zx0, 160);
const remap = new Uint8Array(256);
order.forEach((oldIndex, newIndex) => { remap[oldIndex] = newIndex; });
const orderedPattern = Uint8Array.from(order.flatMap((oldIndex) => [...originalTiles[oldIndex]]));
const remappedFrames = originalFrames.map((frame) => Uint8Array.from(frame, (tile) => remap[tile]));
const pattern = Buffer.from(await zx0.compress(orderedPattern));
const sprites = Buffer.from(await zx0.compress(readDbLabel(source, "SPRITE_MASK_PATTERNS", 384)));
const runtimeSource = renderRuntimeAsm(remappedFrames);
fs.writeFileSync(path.join(path.dirname(input), "earth-globe.pattern.zx0"), pattern);
fs.writeFileSync(path.join(path.dirname(input), "earth-globe-sprites.pattern.zx0"), sprites);
fs.writeFileSync(path.join(path.dirname(input), "earth-globe-runtime.asm"), runtimeSource);
const entries = [
  { path: "earth-globe-runtime.asm", kind: "asm", source: "generated", base64: Buffer.from(runtimeSource).toString("base64") },
  { path: "earth-globe.pattern.zx0", kind: "compressed", codec: "zx0", source: "generated", base64: pattern.toString("base64") },
  { path: "earth-globe-sprites.pattern.zx0", kind: "compressed", codec: "zx0", source: "generated", base64: sprites.toString("base64") },
];

fs.writeFileSync(output, `// Generated by tools/build-earth-globe-assets.mjs.\nexport const earthGlobeProjectFiles = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Wrote ${path.relative(root, output)}: patterns ${pattern.length}, sprites ${sprites.length} ZX0 bytes.`);

function splitTiles(bytes) {
  return Array.from({ length: bytes.length / 8 }, (_, index) => bytes.slice(index * 8, index * 8 + 8));
}

async function optimizeTileOrder(tiles, codec, attempts) {
  const fixed = Array.from({ length: 254 }, (_, index) => index + 1);
  const greedy = [fixed.shift()];
  while (fixed.length) {
    const previous = tiles[greedy.at(-1)];
    let bestAt = 0;
    let bestDistance = Infinity;
    for (let index = 0; index < fixed.length; index += 1) {
      const distance = tileDistance(previous, tiles[fixed[index]]);
      if (distance < bestDistance || (distance === bestDistance && fixed[index] < fixed[bestAt])) {
        bestDistance = distance;
        bestAt = index;
      }
    }
    greedy.push(fixed.splice(bestAt, 1)[0]);
  }
  let best = [0, ...greedy, 255];
  let bestSize = (await codec.compress(flattenTiles(best, tiles))).length;
  const original = Array.from({ length: 256 }, (_, index) => index);
  const originalSize = (await codec.compress(flattenTiles(original, tiles))).length;
  if (originalSize < bestSize) { best = original; bestSize = originalSize; }
  let state = 0x45415254;
  const random = () => {
    state ^= state << 13; state ^= state >>> 17; state ^= state << 5;
    return state >>> 0;
  };
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    const candidate = best.slice();
    const left = 1 + (random() % 254);
    const right = 1 + (random() % 254);
    if ((attempt & 3) === 0) {
      const from = Math.min(left, right);
      const to = Math.max(left, right);
      candidate.splice(from, to - from + 1, ...candidate.slice(from, to + 1).reverse());
    } else {
      [candidate[left], candidate[right]] = [candidate[right], candidate[left]];
    }
    const size = (await codec.compress(flattenTiles(candidate, tiles))).length;
    if (size < bestSize) { best = candidate; bestSize = size; }
  }
  console.log(`Tile-order search: ${originalSize} -> ${bestSize} bytes (${attempts} deterministic mutations).`);
  return best;
}

function flattenTiles(order, tiles) {
  return Uint8Array.from(order.flatMap((index) => [...tiles[index]]));
}

function tileDistance(left, right) {
  let distance = 0;
  for (let index = 0; index < 8; index += 1) distance += popcount(left[index] ^ right[index]);
  return distance;
}

function popcount(value) {
  value -= (value >>> 1) & 0x55;
  value = (value & 0x33) + ((value >>> 2) & 0x33);
  return ((value + (value >>> 4)) & 0x0f);
}

function renderRuntimeAsm(frames) {
  const lines = ["; Generated by tools/build-earth-globe-assets.mjs.", ""];
  frames.forEach((frame, index) => {
    lines.push(`FRAME_${String(index * 2).padStart(2, "0")}H_MAP:`);
    for (let row = 0; row < 8; row += 1) {
      lines.push(`    db ${[...frame.slice(row * 8, row * 8 + 8)].map((value) => `$${value.toString(16).padStart(2, "0").toUpperCase()}`).join(",")}`);
    }
  });
  lines.push("", "EarthDrawFrame:", "    ld b,8", "    ld c,8", "    ld d,8", "    ld e,12", "    push ix", "    push iy", "    call PUT_FRAME", "    pop iy", "    pop ix", "    ret", "");
  return lines.join("\n");
}

function readDbLabel(text, label, count) {
  const start = text.search(new RegExp(`^${label}:`, "m"));
  if (start < 0) throw new Error(`Missing ${label}`);
  const values = [];
  for (const line of text.slice(start).split(/\r?\n/).slice(1)) {
    if (/^[A-Za-z_][A-Za-z0-9_]*:/.test(line.trim())) break;
    for (const match of line.split(";")[0].matchAll(/\$([0-9A-F]{2})/gi)) values.push(Number.parseInt(match[1], 16));
  }
  if (values.length !== count) throw new Error(`${label}: expected ${count} bytes, found ${values.length}`);
  return Uint8Array.from(values);
}
