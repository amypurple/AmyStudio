import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const projectPath = path.join(root, "build", "space-taxi-captioned-voice-demo-faster", "space-taxi-captioned-voice-demo.amy.json");
const outputPath = path.join(root, "studio", "examples-voxpcm-assets.generated.js");
const project = JSON.parse(fs.readFileSync(projectPath, "utf8"));
const files = project.projectFiles.map(file => ({
  path: String(file.path).replace(/^@project\//, ""),
  base64: file.base64,
  kind: "voxpcm",
  source: "Adaptive VoxPCM voice demo"
}));
const output = `// Generated by tools/generate-voxpcm-example-assets.mjs\nexport const spaceTaxiVoiceProjectFiles = ${JSON.stringify(files, null, 2)};\n`;
fs.writeFileSync(outputPath, output, "utf8");
console.log(`Generated ${path.relative(root, outputPath)} with ${files.length} VoxPCM files.`);
