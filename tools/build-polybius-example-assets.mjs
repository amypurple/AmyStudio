import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const assetDirectory = resolve(root, "studio/examples-src/assets/polybius-tunnel");
const names = [
  "shape0.pat.zx0", "shape1.pat.zx0", "shape2.pat.zx0",
  "shape0.pagesA.zx0", "shape1.pagesA.zx0", "shape2.pagesA.zx0",
  "shape0.pagesB.zx0", "shape1.pagesB.zx0", "shape2.pagesB.zx0"
];
const files = names.map((name) => ({
  path: `assets/polybius-tunnel/${basename(name)}`,
  kind: "compressed",
  source: "example",
  base64: readFileSync(resolve(assetDirectory, name)).toString("base64")
}));
const output = `// Generated by tools/build-polybius-example-assets.mjs.\n` +
  `export const polybiusTunnelProjectFiles = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(resolve(root, "studio/examples-polybius-assets.generated.js"), output);
console.log(`Generated ${files.length} Polybius project assets.`);
