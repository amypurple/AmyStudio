import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const libDir = path.join(repoRoot, "src", "alexis_lib");
const compressionDir = path.join(repoRoot, "src", "compression");
const includeDir = path.join(repoRoot, "include");
const outPath = path.join(repoRoot, "studio", "core", "alexisLibrarySources.generated.js");
const checkOnly = process.argv.slice(2).includes("--check");

function toPosix(relPath) {
  return relPath.split(path.sep).join("/");
}

const entries = {};
const excludedResearchSources = new Set([
  "exomizer_vram.asm",
  "rnc2_vram.asm"
]);

function addDirectorySources(dirPath, extensions) {
  if (!fs.existsSync(dirPath)) return;
  for (const name of fs.readdirSync(dirPath).sort()) {
    if (excludedResearchSources.has(name.toLowerCase())) continue;
    const lowered = name.toLowerCase();
    if (!extensions.some((ext) => lowered.endsWith(ext))) continue;
    const fullPath = path.join(dirPath, name);
    const relPath = toPosix(path.relative(repoRoot, fullPath));
    const text = fs.readFileSync(fullPath, "utf8").replace(/\r\n/g, "\n");
    entries[relPath] = text;
  }
}

addDirectorySources(libDir, [".asm"]);
addDirectorySources(compressionDir, [".asm"]);
addDirectorySources(includeDir, [".inc"]);

const banner = [
  "// Auto-generated by tools/generate-alexis-library-source-catalog.mjs",
  "// Browser-side fallback for local Alexis ASM/INC sources.",
  `// Embedded sources: ${Object.keys(entries).length}`
].join("\n");

const output = `${banner}\nexport const alexisLibrarySources = ${JSON.stringify(entries, null, 2)};\n`;
if (checkOnly) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  if (current !== output) {
    console.error(`Stale generated library catalog: ${outPath}`);
    console.error("Run: node tools/generate-alexis-library-source-catalog.mjs");
    process.exit(1);
  }
  console.log(`Library source catalog is current (${Object.keys(entries).length} sources).`);
  process.exit(0);
}
fs.writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${outPath}`);
