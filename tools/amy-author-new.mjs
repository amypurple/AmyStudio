function main() {
  try {
    const args = parseCliArgs(process.argv.slice(2));
    if (!args.name || args.help) {
      console.log("Usage: node tools/amy-author-new.mjs <name> [--title \"Game Title\"] [--dest folder|--output folder]");
      return args.name ? 0 : 2;
    }
    const result = createAuthorProject({ name: args.name, title: args.title, destination: args.destination || args.name });
    console.log(`Amy author new: PASS (${basename(result.project)}, ${result.files.length} source/metadata files)`);
    console.log(`Next: node tools/amy-author-build.mjs "${result.project}"`);
    return 0;
  } catch (error) {
    console.error(`Amy author new: FAIL (${error.message})`);
    return 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) process.exitCode = main();
