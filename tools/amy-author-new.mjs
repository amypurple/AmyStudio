#!/usr/bin/env node
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

export function parseCliArgs(argv) {
  const result = { name: "", title: "", destination: "" };
  const args = [...argv];
  result.name = String(args.shift() || "");
  while (args.length) {
    const flag = args.shift();
    if (flag === "--help") {
      result.help = true;
      continue;
    }
    if (!["--title", "--dest", "--output"].includes(flag)) throw new Error(`unknown option: ${flag}`);
    if (!args.length || String(args[0]).startsWith("--")) throw new Error(`missing value for ${flag}`);
    const value = String(args.shift());
    if (flag === "--title") result.title = value;
    else {
      if (result.destination) throw new Error("use only one of --dest or --output");
      result.destination = value;
    }
  }
  return result;
}

function titleFromName(name) {
  return name.replace(/[-_]+/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function quoted(value) {
  return String(value).replace(/["\r\n]/g, " ").trim();
}

